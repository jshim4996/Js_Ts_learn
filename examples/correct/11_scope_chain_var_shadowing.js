/**
 * 스코프 체인 퀴즈 #2 - var 호이스팅과 섀도잉
 *
 * 문제:
 * var x = 10;
 *
 * function foo() {
 *   console.log(x);
 *   var x = 20;
 *   console.log(x);
 * }
 *
 * foo();
 *
 * 정답: undefined -> 20
 */

// ============================================
// 원본 코드
// ============================================

var x = 10;

function foo() {
  console.log(x);
  var x = 20;
  console.log(x);
}

foo();

// ============================================
// 실행 순서
// ============================================

// 1. 전역: var x = 10
// 2. foo() 호출
// 3. foo 스코프 내 var x 호이스팅 → x = undefined
// 4. console.log(x) → undefined (함수 내부 x 참조)
// 5. x = 20 할당
// 6. console.log(x) → 20

// ============================================
// 핵심 포인트
// ============================================

// - var는 함수 스코프 → 함수 내부 var x가 전역 x를 가림 (shadowing)
// - 스코프 체인은 가장 가까운 스코프에서 먼저 찾음
// - 전역 x = 10은 참조되지 않음

