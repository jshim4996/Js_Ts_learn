/**
 * 스코프 체인 퀴즈 #1 - 기본 스코프 체인
 *
 * 문제:
 * const a = 1;
 *
 * function outer() {
 *   const a = 2;
 *
 *   function inner() {
 *     console.log(a);
 *   }
 *
 *   inner();
 * }
 *
 * outer();
 *
 * 오답: 1 -> 2 (두 개 출력된다고 착각)
 * 정답: 2
 */

// ============================================
// 원본 코드
// ============================================

const a = 1;

function outer() {
  const a = 2;

  function inner() {
    console.log(a);
  }

  inner();
}

outer();

// ============================================
// 스코프 체인 동작
// ============================================

// inner() 함수가 a를 찾는 순서:
// 1. inner 스코프에서 a 찾기 → 없음
// 2. outer 스코프에서 a 찾기 → const a = 2 발견! → 2 출력

// 전역의 a = 1은 참조되지 않음 (outer 스코프에서 이미 찾았으므로)

// ============================================
// 스코프 체인 규칙
// ============================================

// 1. 현재 스코프에서 변수를 찾음
// 2. 없으면 바로 상위 스코프에서 찾음
// 3. 찾으면 거기서 멈춤 (더 이상 상위로 안 감)
// 4. 전역까지 없으면 ReferenceError

